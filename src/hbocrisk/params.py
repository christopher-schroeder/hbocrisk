def _piecewise(pieces, default=1.0):
    """pieces: list of (lo, hi_inclusive, f) with f(age array) -> RR."""
    rr = np.full(MAX_AGE, default, dtype=float)
    for lo, hi, f in pieces:
        sel = (AGES >= lo) & (AGES <= hi)
        rr[sel] = f(AGES[sel].astype(float))
    return rr


def _const(v):
    return lambda a: np.full_like(a, v, dtype=float)


def _loglin(a0, b):
    return lambda a: np.exp(a0 + b * a)



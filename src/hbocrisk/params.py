def _parse_table(txt):
    rows = np.array([[float(v) for v in line.split()] for line in txt.strip().splitlines()])
    full = np.empty((MAX_AGE, rows.shape[1] - 1))
    full[20:] = rows[:, 1:]
    full[:20] = rows[0, 1:]          # ages below 20: as at age 20
